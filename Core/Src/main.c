void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART2)
    {
        /* 内核未启动或队列未创建时直接忽略，避免 HardFault */
        if (osKernelGetState() == osKernelRunning && BleRxQueueHandle != NULL)
        {
            if (osMessageQueuePut(BleRxQueueHandle, &g_ble_rx, 0, 0) != osOK) {
                g_ble_drop_cnt++;
            }
        }
        HAL_UART_Receive_IT(&huart2, &g_ble_rx, 1);
    }
}

void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART2)
    {
        __HAL_UART_CLEAR_OREFLAG(huart);
        __HAL_UART_CLEAR_NEFLAG(huart);
        __HAL_UART_CLEAR_FEFLAG(huart);
        huart->ErrorCode = HAL_UART_ERROR_NONE;
        huart->RxState = HAL_UART_STATE_READY;
        HAL_UART_Receive_IT(huart, &g_ble_rx, 1);
    }
}
